"""Character Autogeneration service."""

from typing import TYPE_CHECKING

from vweb.api_client.constants import (
    AbilityFocus,
    AutoGenExperienceLevel,
    CharacterClass,
    CharacterType,
)
from vweb.api_client.models import (
    Character,
    ChargenSessionFinalizeDTO,
    ChargenSessionResponse,
    CreateAutogenerateDTO,
)
from vweb.api_client.routes import Routes
from vweb.api_client.services.base import BaseService

if TYPE_CHECKING:
    from vweb.api_client.client import VClient


class CharacterAutogenService(BaseService):
    """Service for interacting with the Character Autogeneration API."""

    def __init__(self, client: "VClient", company_id: str, on_behalf_of: str) -> None:
        """Initialize the service.

        Args:
            client: The VClient instance to use for requests.
            company_id: The ID of the company to operate within.
            on_behalf_of: User ID to impersonate via On-Behalf-Of header.
        """
        super().__init__(client, on_behalf_of=on_behalf_of, company_id=company_id)

    # -------------------------------------------------------------------------
    # Character Autogeneration Methods
    # -------------------------------------------------------------------------

    def generate_character(
        self,
        *,
        campaign_id: str,
        character_type: CharacterType,
        character_class: CharacterClass | None = None,
        experience_level: AutoGenExperienceLevel | None = None,
        skill_focus: AbilityFocus | None = None,
        concept_id: str | None = None,
        vampire_clan_id: str | None = None,
        werewolf_tribe_id: str | None = None,
        werewolf_auspice_id: str | None = None,
    ) -> Character:
        """Generate a character.

        Args:
            campaign_id: The ID of the campaign to generate the character for.
            character_type: The type of character to generate.
            character_class: The class of character to generate.
            experience_level: The experience level of character to generate.
            skill_focus: The skill focus of character to generate.
            concept_id: The concept ID of character to generate.
            vampire_clan_id: The vampire clan ID of character to generate.
            werewolf_tribe_id: The werewolf tribe ID of character to generate.
            werewolf_auspice_id: The werewolf auspice ID of character to generate.

        Returns:
            The generated character.

        Raises:
            RequestValidationError: If the input parameters fail client-side validation.
            ValidationError: If the request data is invalid.
            AuthorizationError: If you don't have appropriate access.
        """
        body = self._validate_request(
            CreateAutogenerateDTO,
            character_type=character_type,
            character_class=character_class,
            experience_level=experience_level,
            skill_focus=skill_focus,
            concept_id=concept_id,
            vampire_clan_id=vampire_clan_id,
            werewolf_tribe_id=werewolf_tribe_id,
            werewolf_auspice_id=werewolf_auspice_id,
        )
        return self._call(
            Routes.CHARACTERS_AUTOGENERATE,
            json=body.model_dump(exclude_none=True, exclude_unset=True, mode="json"),
            params={"campaign_id": campaign_id},
        )

    def start_chargen_session(self, *, campaign_id: str) -> ChargenSessionResponse:
        """Start a chargen session.

        Args:
            campaign_id: The ID of the campaign to start the chargen session for.

        Returns:
            The chargen session response.
        """
        return self._call(Routes.CHARACTERS_CHARGEN_START, params={"campaign_id": campaign_id})

    def finalize_chargen_session(self, session_id: str, selected_character_id: str) -> Character:
        """Finalize a chargen session."""
        body = self._validate_request(
            ChargenSessionFinalizeDTO,
            session_id=session_id,
            selected_character_id=selected_character_id,
        )
        return self._call(
            Routes.CHARACTERS_CHARGEN_FINALIZE,
            json=body.model_dump(exclude_none=True, exclude_unset=True, mode="json"),
        )

    def list_all(self) -> list[ChargenSessionResponse]:
        """List the On-Behalf-Of user's chargen sessions across every campaign.

        Returns:
            The user's chargen sessions. Filter by ``campaign_id`` to scope them.
        """
        return self._list(Routes.CHARACTERS_CHARGEN_SESSIONS_LIST)

    def get(self, session_id: str) -> ChargenSessionResponse:
        """Retrieve a single chargen session by ID.

        Args:
            session_id: The ID of the session to retrieve.

        Returns:
            The chargen session matching the given session_id.
        """
        return self._call(Routes.CHARACTERS_CHARGEN_SESSION_GET, session_id=session_id)
